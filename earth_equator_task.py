def distance_from_equator(latitude):
  miles_per_degree=69
  return abs(latitude)*miles_per_degree
def main():
  cities={"New Delhi":28,"Paris":48,"Rome":41,"Brisbane":-27,"Berlin":52,"Beunos Aires":-34,"London":51,"New York":40,}
  distances={city:distance_from_equator(latitude) for city,latitude in cities.items()}
  closest_city=min(distances,key=distances.get)
  farthest_city=max(distances,key=distances.get)
  print("Distances from equator in miles: ")
  for city, dist in distances.items():
    print(f"{city}: {dist:.2f} miles")
  print(f"\nFarthest from equator: {farthest_city}")
  print(f"Closest to equator: {closest_city}")
if __name__=="__main__":
 main()